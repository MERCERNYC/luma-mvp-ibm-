/* ═══════════════════════════════════════════════════════════════
   Gmail message normalizer
   ───────────────────────────────────────────────────────────────
   Converts a raw Gmail API message object into the ClassifyInput
   shape that LUMA v7 / WatsonxAgent already understands.

   This is the sole seam between Gmail and the V1 pipeline.
   Nothing downstream changes — /api/agent/classify, useClassifiedEmails,
   and the dashboard are all untouched.

   Two representations are produced for every HTML email
   ────────────────────────────────────────────────────
   body (cleanBody)
     Clean plain text. All HTML stripped, URLs removed, entities
     decoded, tracking noise removed.
     → sent to watsonx / LUMA v7 for classification

   displayBody
     Sanitized HTML. Dangerous tags/attrs removed by an allow-list
     sanitizer. Safe to render in the reading pane.
     → displayed in EmailPane only, NEVER sent to watsonx

   MIME extraction priority
   ────────────────────────
   Marketing / HTML emails typically have this MIME tree:

     multipart/alternative
       ├── text/plain   ← machine-generated by the sender's ESP;
       │                   contains Markdown-style links like
       │                   [Shop Women's](https://tracking.url)
       └── text/html    ← the real readable content

   The old extractor returned the first text/plain it found, which
   is exactly that noisy ESP-generated text.

   New strategy for cleanBody (in priority order):
     1. text/plain that is "clean" — no markdown URL patterns.
        Human-written plain-text replies fall here.
     2. text/html → strip tags, keep visible text + link labels,
        drop all URLs, decode entities, clean whitespace.
     3. Noisy text/plain as last resort (better than nothing).
     4. Gmail snippet fallback.

   displayBody is produced from text/html when available; absent
   for plain-text-only emails.
   ═══════════════════════════════════════════════════════════════ */

import type { ClassifyInput } from "@/services/agent/types";

// ── Gmail REST API types (subset we need) ───────────────────────

export interface GmailMessageHeader {
  name:  string;
  value: string;
}

export interface GmailMessagePart {
  mimeType: string;
  body:     { data?: string; size: number };
  parts?:   GmailMessagePart[];
}

export interface GmailMessage {
  id:               string;
  threadId:         string;
  internalDate:     string; /* Unix ms as a string */
  payload:          GmailMessagePart & { headers: GmailMessageHeader[] };
  snippet:          string;
}

// ── Helpers ──────────────────────────────────────────────────────

function getHeader(msg: GmailMessage, name: string): string {
  return (
    msg.payload.headers.find(
      (h) => h.name.toLowerCase() === name.toLowerCase(),
    )?.value ?? ""
  );
}

/** Pull display name out of "Name <email>" or return address as-is */
function parseSender(from: string): { name: string; email: string } {
  const match = from.match(/^(.+?)\s*<([^>]+)>/);
  if (match) return { name: match[1].trim(), email: match[2].trim() };
  return { name: from.trim(), email: from.trim() };
}

// ── MIME part collectors ─────────────────────────────────────────

/** Collect ALL text/plain parts from the MIME tree (decoded). */
function collectPlainParts(part: GmailMessagePart): string[] {
  const results: string[] = [];
  if (part.mimeType === "text/plain" && part.body.data) {
    results.push(Buffer.from(part.body.data, "base64url").toString("utf-8"));
  }
  for (const child of part.parts ?? []) {
    results.push(...collectPlainParts(child));
  }
  return results;
}

/** Collect ALL text/html parts from the MIME tree (decoded). */
function collectHtmlParts(part: GmailMessagePart): string[] {
  const results: string[] = [];
  if (part.mimeType === "text/html" && part.body.data) {
    results.push(Buffer.from(part.body.data, "base64url").toString("utf-8"));
  }
  for (const child of part.parts ?? []) {
    results.push(...collectHtmlParts(child));
  }
  return results;
}

// ── HTML → clean plain text ──────────────────────────────────────

/**
 * Convert an HTML email body into clean readable text.
 *
 * Rules:
 *  - <a href="...">Label</a>  →  "Label"   (URL dropped entirely)
 *  - <br>, <p>, <div>, block tags  →  newline
 *  - <style>, <script>, <head>  →  removed entirely with content
 *  - HTML entities decoded
 *  - Tracking pixels / src-only images → removed
 *  - Excessive whitespace collapsed
 */
function htmlToCleanText(html: string): string {
  let text = html;

  // 1. Nuke style/script/head blocks (and their content) entirely
  text = text.replace(/<(style|script|head)[^>]*>[\s\S]*?<\/\1>/gi, " ");

  // 2. Links: keep visible label, drop URL
  //    <a ...>Label</a>  →  Label
  text = text.replace(/<a\b[^>]*>([\s\S]*?)<\/a>/gi, (_, inner) => {
    const label = inner.replace(/<[^>]+>/g, "").trim();
    return label ? label : "";
  });

  // 3. Images: use alt text if present, otherwise nothing
  text = text.replace(/<img\b[^>]*>/gi, (tag) => {
    const alt = tag.match(/\balt=["']([^"']*)["']/i)?.[1]?.trim();
    return alt ? ` ${alt} ` : " ";
  });

  // 4. Block-level elements → newline
  text = text.replace(
    /<\/?(p|div|section|article|header|footer|h[1-6]|li|tr|blockquote|pre)[^>]*>/gi,
    "\n",
  );

  // 5. <br> → newline
  text = text.replace(/<br\s*\/?>/gi, "\n");

  // 6. Strip all remaining tags
  text = text.replace(/<[^>]+>/g, "");

  // 7. Decode HTML entities
  text = decodeHtmlEntities(text);

  // 8. Collapse runs of blank lines to a single blank line
  text = text.replace(/\n{3,}/g, "\n\n");

  // 9. Remove lines that are solely a bare URL (tracking/view-in-browser)
  text = text.replace(/^[ \t]*https?:\/\/\S+[ \t]*$/gm, "");

  // 10. Remove remaining inline bare URLs
  text = text.replace(/https?:\/\/\S+/g, "");

  // 11. Remove ESP boilerplate preheader lines
  text = text.replace(
    /^[#*\-]*[ \t]*(if (this|you).{0,60}(displayed|view|click)|to view this email|having trouble viewing|view (this|email) (in|as|online)|can't see this|web version|view online|view in browser).*/gim,
    "",
  );

  // 12. Collapse horizontal whitespace on each line
  text = text
    .split("\n")
    .map((line) => line.replace(/[ \t]+/g, " ").trim())
    .join("\n");

  // 13. Re-collapse blank lines after removals, then trim
  return text.replace(/\n{3,}/g, "\n\n").trim();
}

// ── HTML entity decoder ──────────────────────────────────────────

/** Decode common named entities + numeric character references. */
function decodeHtmlEntities(text: string): string {
  const named: Record<string, string> = {
    "&amp;":   "&",
    "&lt;":    "<",
    "&gt;":    ">",
    "&quot;":  '"',
    "&#39;":   "'",
    "&apos;":  "'",
    "&nbsp;":  " ",
    "&ndash;": "–",
    "&mdash;": "—",
    "&lsquo;": "'",
    "&rsquo;": "'",
    "&ldquo;": '"',
    "&rdquo;": '"',
    "&bull;":  "•",
    "&hellip;":"…",
    "&copy;":  "©",
    "&reg;":   "®",
    "&trade;": "™",
    "&times;": "×",
    "&divide;":"÷",
  };

  return text
    // Named entities
    .replace(/&[a-z]+;/gi, (e) => named[e.toLowerCase()] ?? e)
    // Decimal numeric references &#160;
    .replace(/&#(\d+);/g, (_, n) => String.fromCharCode(Number(n)))
    // Hex numeric references &#xA0;
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCharCode(parseInt(h, 16)));
}

// ── "Clean" plain-text detector ─────────────────────────────────

/**
 * Returns true if this plain-text block looks human-written and clean.
 * An ESP-generated plain part always has patterns like [Label](URL)
 * scattered through it; a human-written reply almost never does.
 *
 * Heuristic: if the ratio of markdown-link patterns to total lines
 * is above 15%, treat the part as "noisy" and prefer HTML.
 */
function isCleanPlainText(text: string): boolean {
  const lines = text.split("\n").filter((l) => l.trim().length > 0);
  if (lines.length === 0) return false;

  // Count lines that contain at least one [text](url) markdown link
  const noisyLines = lines.filter((l) => /\[[^\]]+\]\(https?:\/\/[^)]+\)/.test(l));
  const ratio = noisyLines.length / lines.length;
  return ratio < 0.15;
}

// ── Body extractor ───────────────────────────────────────────────

/**
 * Extract the best readable body from a Gmail MIME message.
 *
 * Priority:
 *  1. text/plain that passes the "clean" heuristic (human replies)
 *  2. text/html → stripped to clean plain text
 *  3. text/plain even if noisy (last resort)
 */
function extractBody(part: GmailMessagePart): string {
  const plainParts = collectPlainParts(part);
  const htmlParts  = collectHtmlParts(part);

  // 1. Prefer a clean text/plain part
  for (const plain of plainParts) {
    if (isCleanPlainText(plain) && plain.trim().length > 0) {
      return cleanPlainText(plain);
    }
  }

  // 2. Fall back to HTML → stripped clean text
  if (htmlParts.length > 0) {
    const cleaned = htmlToCleanText(htmlParts.join("\n"));
    if (cleaned.length > 0) return cleaned;
  }

  // 3. Last resort: noisy plain text (still better than nothing)
  for (const plain of plainParts) {
    const t = plain.trim();
    if (t.length > 0) return cleanPlainText(t);
  }

  return "";
}

/**
 * Tidy up a plain-text body: decode entities, strip tracking noise,
 * collapse whitespace. Meaningful content (dates, prices, instructions,
 * confirmation numbers) is always preserved.
 */
function cleanPlainText(text: string): string {
  return decodeHtmlEntities(text)
    .replace(/\r\n/g, "\n")
    // Remove lines that are solely a bare URL (tracking/view-in-browser links)
    .replace(/^[ \t]*https?:\/\/\S+[ \t]*$/gm, "")
    // Remove common ESP boilerplate preheader lines
    // e.g. "# If this email is not displayed properly, click here"
    // e.g. "To view this email as a web page, click here"
    // e.g. "Having trouble viewing this email?"
    .replace(/^[#*\-]*[ \t]*(if (this|you).{0,60}(displayed|view|click)|to view this email|having trouble viewing|view (this|email) (in|as|online)|can't see this|web version|view online|view in browser).*/gim, "")
    // Remove Markdown-style links entirely: [label](url) → label
    .replace(/\[([^\]]*)\]\(https?:\/\/[^)]+\)/g, "$1")
    // Remove any remaining bare URLs that survived
    .replace(/https?:\/\/\S+/g, "")
    .replace(/[ \t]+/g, " ")                  // collapse horizontal whitespace
    .replace(/\n{3,}/g, "\n\n")               // collapse excess blank lines
    .trim();
}

// ── HTML sanitizer (allow-list) ─────────────────────────────────

/**
 * Sanitize an HTML email for safe rendering in the reading pane.
 *
 * Strategy: allow-list of safe tags and attributes.
 * Everything not on the list is removed (tags stripped, attrs dropped).
 *
 * Removed entirely (tag + all content):
 *   script, style, head, link, meta, object, embed, applet,
 *   iframe, frame, frameset, form, input, button, select, textarea
 *
 * Removed (tag only, content kept):
 *   everything else not in SAFE_TAGS
 *
 * Attribute handling:
 *   - href/src: keep only http/https/mailto; drop javascript: and data:
 *   - All on* event handlers removed unconditionally
 *   - style attributes: stripped entirely (avoids CSS injection)
 *   - Links get target="_blank" rel="noopener noreferrer"
 *   - Images get loading="lazy" and a max-width cap inline
 */

const REMOVE_WITH_CONTENT =
  /<!--[\s\S]*?-->|<(script|style|head|link|meta|object|embed|applet|iframe|frame|frameset|form|input|button|select|textarea)\b[^>]*>[\s\S]*?<\/\1>|<(script|style|head|link|meta|object|embed|applet|iframe|frame|frameset|form|input|button|select|textarea)\b[^>]*\/?>/gi;

const SAFE_TAGS = new Set([
  "a", "abbr", "address", "article", "aside", "b", "bdi", "bdo",
  "blockquote", "br", "caption", "cite", "code", "col", "colgroup",
  "data", "dd", "del", "details", "dfn", "div", "dl", "dt", "em",
  "figcaption", "figure", "footer", "h1", "h2", "h3", "h4", "h5", "h6",
  "header", "hr", "i", "img", "ins", "kbd", "li", "main", "mark",
  "nav", "ol", "p", "pre", "q", "rp", "rt", "ruby", "s", "samp",
  "section", "small", "span", "strong", "sub", "summary", "sup",
  "table", "tbody", "td", "tfoot", "th", "thead", "time", "tr",
  "u", "ul", "var", "wbr",
]);

// Attributes allowed per tag (or globally via "*")
const SAFE_ATTRS: Record<string, Set<string>> = {
  "*":   new Set(["class", "id", "lang", "dir", "aria-label", "aria-hidden",
                  "role", "title", "colspan", "rowspan", "width", "height",
                  "align", "valign", "bgcolor", "color", "border",
                  "cellpadding", "cellspacing"]),
  "a":   new Set(["href"]),
  "img": new Set(["src", "alt", "width", "height"]),
  "td":  new Set(["colspan", "rowspan", "width", "height", "align", "valign",
                  "bgcolor", "nowrap"]),
  "th":  new Set(["colspan", "rowspan", "width", "height", "align", "valign",
                  "scope"]),
  "col": new Set(["span", "width"]),
  "ol":  new Set(["start", "type"]),
  "li":  new Set(["value"]),
  "hr":  new Set(["width", "size"]),
};

function sanitizeHtml(html: string): string {
  // 1. Remove dangerous blocks wholesale
  let out = html.replace(REMOVE_WITH_CONTENT, " ");

  // 2. Process every remaining tag
  out = out.replace(/<(\/?)([a-zA-Z][a-zA-Z0-9]*)([^>]*)>/g, (
    _full, slash, rawTag, rawAttrs,
  ) => {
    const tag = rawTag.toLowerCase();

    // Unknown tag → drop the tag, keep its content
    if (!SAFE_TAGS.has(tag)) return "";

    // Closing tag — no attrs needed
    if (slash === "/") return `</${tag}>`;

    // Self-closing void elements
    const isVoid = ["br","hr","img","col","wbr"].includes(tag);

    // Build safe attribute string
    const globalAllowed = SAFE_ATTRS["*"];
    const tagAllowed    = SAFE_ATTRS[tag] ?? new Set<string>();

    // Parse attrs: handle both quoted and unquoted values
    const attrPairs: string[] = [];
    const attrRe = /([a-zA-Z][a-zA-Z0-9\-:]*)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|(\S+)))?/g;
    let m: RegExpExecArray | null;

    while ((m = attrRe.exec(rawAttrs)) !== null) {
      const attrName  = m[1].toLowerCase();
      const attrValue = (m[2] ?? m[3] ?? m[4] ?? "").trim();

      // Drop ALL event handlers unconditionally
      if (attrName.startsWith("on")) continue;
      // Drop style — too much CSS injection surface
      if (attrName === "style") continue;

      if (!globalAllowed.has(attrName) && !tagAllowed.has(attrName)) continue;

      if (attrName === "href") {
        if (!/^(https?:|mailto:)/i.test(attrValue)) continue;
        attrPairs.push(
          `href="${attrValue}" target="_blank" rel="noopener noreferrer"`,
        );
        continue;
      }

      if (attrName === "src") {
        // Allow only http/https image src — drops data: tracking pixels
        if (!/^https?:\/\//i.test(attrValue)) continue;
        attrPairs.push(`src="${attrValue}" loading="lazy"`);
        continue;
      }

      attrPairs.push(`${attrName}="${attrValue}"`);
    }

    const attrStr = attrPairs.length > 0 ? " " + attrPairs.join(" ") : "";
    return isVoid ? `<${tag}${attrStr}>` : `<${tag}${attrStr}>`;
  });

  // 3. Wrap in a scoping div with baseline email-friendly resets
  return `<div class="luma-email-html">${out}</div>`;
}

// ── Main export ──────────────────────────────────────────────────

/**
 * Normalise one Gmail API message into a ClassifyInput.
 * Called by GET /api/gmail/messages for each message in the batch.
 *
 * Produces:
 *   body        — clean plain text → sent to watsonx / LUMA v7
 *   displayBody — sanitized HTML   → reading pane only, never watsonx
 */
export function gmailMessageToClassifyInput(msg: GmailMessage): ClassifyInput {
  const from    = getHeader(msg, "from");
  const subject = getHeader(msg, "subject");
  const { name: sender, email: senderEmail } = parseSender(from);

  const htmlParts = collectHtmlParts(msg.payload);

  // cleanBody — plain text for classification
  const body = extractBody(msg.payload).trim();

  // displayBody — sanitized HTML for the reading pane (only when HTML exists)
  const displayBody = htmlParts.length > 0
    ? sanitizeHtml(htmlParts.join("\n"))
    : undefined;

  // snippet is the short preview Google already generates (~100 chars)
  const preview = decodeHtmlEntities(
    msg.snippet.replace(/&#(\d+);/g, (_, c) => String.fromCharCode(Number(c))),
  );

  return {
    id:          msg.id,
    subject:     subject || "(no subject)",
    preview:     preview.slice(0, 120),
    body:        body || preview,   // fall back to snippet if body is empty
    displayBody,
    sender,
    senderEmail,
  };
}
